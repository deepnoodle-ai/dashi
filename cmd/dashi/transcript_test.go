package main

import (
	"fmt"
	"os"
	"strings"
	"testing"

	"github.com/deepnoodle-ai/dashi"
	"github.com/deepnoodle-ai/dashi/cmd/dashi/session"
)

// TestWriteTranscript runs a steer, a queued prompt, and a crash-then-cancel
// recovery on the scripted client and, when DASHI_TRANSCRIPT names a file,
// writes what the terminal showed there as Markdown.
func TestWriteTranscript(t *testing.T) {
	var doc strings.Builder
	scene := func(title string, typed []string, shown string) {
		fmt.Fprintf(&doc, "## %s\n\nTyped, in order:\n\n", title)
		for _, line := range typed {
			fmt.Fprintf(&doc, "- `%s`\n", line)
		}
		fmt.Fprintf(&doc, "\nShown:\n\n```text\n%s```\n\n", shown)
	}

	// A steer while the turn runs, and a prompt queued for after it.
	started, release := make(chan struct{}), make(chan struct{})
	h := newHarness(t,
		hold(started, release, callTool("c1", "list_directory", `{}`)),
		say("Plan B it is: the fix belongs in parser.go, which I changed."),
		say("All 42 tests pass."),
	)
	h.app.ctrl.Input("fix the failing parser test")
	<-started
	h.app.ctrl.Input("use plan B: start from parser.go")
	h.app.ctrl.Input("/queue run the tests")
	close(release)
	h.app.ctrl.Wait()
	text := h.ui.text()
	mustHave(t, text, "steer delivered: use plan B")
	mustHave(t, text, "> run the tests")
	mustHave(t, text, "All 42 tests pass.")
	scene("A steer and a queued prompt", []string{
		"fix the failing parser test",
		"use plan B: start from parser.go   (while turn 1 runs: a steer)",
		"/queue run the tests               (while turn 1 runs)",
	}, text)

	// The process exits while a command runs; a new process refuses a new
	// prompt until the user discards the turn.
	var runs atomicCounter
	withNoteTool(t, &runs)
	h = newHarness(t,
		callTool("c1", "write_note", `{"text":"deploy v2"}`),
		say("Starting over from a clean state."),
	)
	h.app.eng.Close()
	h.recorder = func(rec *session.Recorder) dashi.Recorder {
		return &crashAfterToolStart{Recorder: rec}
	}
	h.ui = newRecorderUI()
	h.build(Options{Resume: true})
	h.input("write the deploy note")
	crashed := h.ui.text()
	h.app.eng.Close()
	scene("Process 1: the process exits during a command", []string{
		"write the deploy note",
		"(the process exits after write_note starts; its result is never recorded)",
	}, crashed)

	h.recorder = nil
	h.ui = newRecorderUI()
	h.build(Options{Resume: true})
	h.app.ctrl.Open()
	h.input("start over")
	h.input("/discard")
	h.input("start over")
	text = h.ui.text()
	mustHave(t, text, "may still be running")
	mustHave(t, text, "Turn 1 canceled.")
	mustHave(t, text, "Starting over from a clean state.")
	view, err := dashi.Replay(h.turn(1))
	if err != nil {
		t.Fatal(err)
	}
	scene("Process 2: dashi --resume", []string{
		"start over   (refused: the command may still be running)",
		"/discard",
		"start over",
	}, text)
	fmt.Fprintf(&doc, "The record of turn 1 after `/discard`: stop `%s` (%q); "+
		"call c1 is `%s`, never settled. Turns in the session: %d.\n",
		view.Stop.Kind, view.Stop.Reason, view.Tools["c1"].Status, h.turns())

	path := os.Getenv("DASHI_TRANSCRIPT")
	if path == "" {
		return
	}
	header := "# CLI transcript: steering, the queue, and crash recovery\n\n" +
		"Generated by `DASHI_TRANSCRIPT=<file> go test -run " +
		"TestWriteTranscript ./` in `cmd/dashi`: the real CLI controller, " +
		"engine, `dashi.Session`, and filerecorder, on a scripted model " +
		"client. The shown text is the line-mode rendering of every block " +
		"(`FormatBlock`), after the last update of each.\n\n"
	if err := os.WriteFile(path, []byte(header+doc.String()), 0o600); err != nil {
		t.Fatal(err)
	}
}
