// InteractionsAPI identifies the Gemini Interactions image and Omni video
// route.
const InteractionsAPI = "google.interactions"

// DefaultInteractionsEndpoint is the API-key Interactions destination.
const DefaultInteractionsEndpoint = "https://generativelanguage.googleapis.com/v1beta/interactions"

const maxInteractionsResponseBytes = 64 << 20

// InteractionsMediaConfig describes a single API-key destination. Model
// evidence
// belongs to this endpoint; GenerateContent and Veo evidence is not portable.
type InteractionsMediaConfig struct {
	Provider         string
	APIKey           string
	Endpoint         string
	Client           *http.Client
	ImageModels      map[string]media.ModelInfo
	VideoModels      map[string]media.ModelInfo
	CapabilityPolicy model.CapabilityPolicy
}

// InteractionsMediaClient makes synchronous image and Omni video calls. The
// host retains prepared requests and generated bytes; the client stores
// neither.
type InteractionsMediaClient struct {
	config      InteractionsMediaConfig
	noKey       error
	imageModels map[string]media.ModelInfo
	videoModels map[string]media.ModelInfo
}

var (
	_ media.ImageClient     = (*InteractionsMediaClient)(nil)
	_ media.VideoCallClient = (*InteractionsMediaClient)(nil)
)

// NewInteractionsMedia snapshots destination configuration and model evidence.
func NewInteractionsMedia(
	config InteractionsMediaConfig,
) (*InteractionsMediaClient, error) {
	if config.Endpoint == "" {
		config.Endpoint = DefaultInteractionsEndpoint
	}
	if config.Provider == "" {
		if config.Endpoint != DefaultInteractionsEndpoint {
			return nil, errors.New("gemini: custom Interactions endpoint requires provider identity")
		}
		config.Provider = "google"
	}
	// The Gemini key is read only for the "google" destination, so a client
	// for another provider never sends it elsewhere.
	if config.APIKey == "" && config.Provider == "google" {
		config.APIKey = cmp.Or(
			os.Getenv("GEMINI_API_KEY"),
			os.Getenv("GOOGLE_API_KEY"),
		)
	}
	u, err := url.Parse(config.Endpoint)
	if err != nil ||
		u.Host == "" ||
		(u.Scheme != "https" &&
			u.Scheme != "http") ||
		u.User != nil || u.RawQuery != "" || u.Fragment != "" || !strings.HasSuffix(
		u.Path,
		"/interactions",
	) {
		return nil, errors.New("gemini: invalid Interactions endpoint")
	}
	if !config.CapabilityPolicy.Valid() {
		return nil, errors.New("gemini: invalid unknown Interactions capability policy")
	}
	if config.Client != nil {
		client := *config.Client
		config.Client = &client
	}
	p := &InteractionsMediaClient{
		config: config,
		noKey: mediaNoKey(
			config.APIKey,
			config.Endpoint == DefaultInteractionsEndpoint &&
				config.Client == nil,
		),
		imageModels: make(map[string]media.ModelInfo, len(config.ImageModels)),
		videoModels: make(map[string]media.ModelInfo, len(config.VideoModels)),
	}
	for name, info := range config.ImageModels {
		if err := validateInteractionsModel(
			name,
			info,
			config.Endpoint,
			true,
		); err != nil {
			return nil, err
		}
		p.imageModels[name] = info.Clone()
	}
	for name, info := range config.VideoModels {
		if err := validateInteractionsModel(
			name,
			info,
			config.Endpoint,
			false,
		); err != nil {
			return nil, err
		}
		p.videoModels[name] = info.Clone()
	}
	p.config.ImageModels = nil
	p.config.VideoModels = nil
	return p, nil
}

func validateInteractionsModel(
	name string,
	info media.ModelInfo,
	endpoint string,
	image bool,
) error {
	if name == "" {
		return errors.New("gemini: Interactions model name is required")
	}
	if err := info.Validate(); err != nil {
		return fmt.Errorf("gemini: Interactions model %q: %w", name, err)
	}
	if info.Evidence.Model != name ||
		info.Evidence.API != InteractionsAPI ||
		info.Evidence.Endpoint != endpoint {
		return fmt.Errorf(
			"gemini: Interactions model %q evidence does not match its API endpoint",
			name,
		)
	}
	if image && info.Image == nil || !image && info.Video == nil {
		return fmt.Errorf(
			"gemini: Interactions model %q lacks operation capabilities",
			name,
		)
	}
	return nil
}

// Provider returns the configured destination identity.
func (p *InteractionsMediaClient) Provider() string {
	return p.config.Provider
}

// ImageModelInfo returns detached image capability evidence.
func (p *InteractionsMediaClient) ImageModelInfo(
	name string,
) (media.ModelInfo, bool) {
	info, ok := p.imageModels[name]
	return info.Clone(), ok
}

// VideoModelInfo returns detached video capability evidence.
func (p *InteractionsMediaClient) VideoModelInfo(
	name string,
) (media.ModelInfo, bool) {
	info, ok := p.videoModels[name]
	return info.Clone(), ok
}

func (p *InteractionsMediaClient) origin(name string) content.Origin {
	scopeData, _ := json.Marshal([]string{
		InteractionsAPI,
		p.config.Endpoint,
		p.config.APIKey,
	})
	sum := sha256.Sum256(scopeData)
	return content.Origin{
		Provider: p.Provider(),
		API:      InteractionsAPI,
		Model:    name,
		Scope:    fmt.Sprintf("%x", sum),
	}
}

func (p *InteractionsMediaClient) failure(
	category media.ErrorCategory,
	format string,
	args ...any,
) error {
	return mediaFailure(p.Provider(), category, format, args...)
}

// Interactions calls return base64 inline media as JSON. Bound that JSON
// separately from Veo's binary Files download.
func (p *InteractionsMediaClient) do(
	ctx context.Context,
	body []byte,
) ([]byte, error) {
	if p.noKey != nil {
		return nil, p.noKey
	}
	return doGeminiMedia(
		ctx,
		p.Provider(),
		p.config.APIKey,
		p.config.Client,
		http.MethodPost,
		p.config.Endpoint,
		body,
		"application/json",
		maxInteractionsResponseBytes,
		false,
	)
}

type interactionResponse struct {
	ID     string          `json:"id"`
	Model  string          `json:"model"`
	Status string          `json:"status"`
	Usage  json.RawMessage `json:"usage"`
	Steps  []struct {
		Type    string `json:"type"`
		Content []struct {
			Type     string `json:"type"`
			Text     string `json:"text"`
			MIMEType string `json:"mime_type"`
			Data     string `json:"data"`
			URI      string `json:"uri"`
		} `json:"content"`
	} `json:"steps"`
}

func (p *InteractionsMediaClient) decode(
	raw []byte,
	kind media.Kind,
	requested string,
) (media.Result, error) {
	var response interactionResponse
	if err := json.Unmarshal(raw, &response); err != nil {
		return media.Result{}, p.failure(
			media.ErrorProtocol,
			"decode Interactions response: %w",
			err,
		)
	}
	result := media.Result{
		Kind:       kind,
		Requested:  model.ModelRef{Provider: p.Provider(), Model: requested},
		API:        InteractionsAPI,
		ResponseID: response.ID,
		RawUsage:   media.ReportedUsage(response.Usage),
	}
	if response.Model != "" {
		result.Served = model.ModelRef{Provider: p.Provider(), Model: response.Model}
	}
	for _, step := range response.Steps {
		if step.Type != "model_output" {
			continue
		}
		for _, part := range step.Content {
			switch part.Type {
			case "text":
				result.Content = append(result.Content, content.TextBlock(part.Text))
			case "image", "video":
				if part.URI != "" {
					return result, p.failure(
						media.ErrorProtocol,
						"Interactions returned URI delivery for an inline request",
					)
				}
				if part.MIMEType == "" || !strings.HasPrefix(
					part.MIMEType,
					part.Type+"/",
				) {
					return result, p.failure(
						media.ErrorProtocol,
						"Interactions %s has invalid MIME type %q",
						part.Type,
						part.MIMEType,
					)
				}
				data, err := base64.StdEncoding.DecodeString(part.Data)
				if err != nil || len(data) == 0 {
					return result, p.failure(
						media.ErrorProtocol,
						"decode Interactions %s: %v",
						part.Type,
						err,
					)
				}
				source := content.Source{Data: data, MIMEType: part.MIMEType}
				if part.Type == "image" {
					result.Content = append(result.Content, content.ImageBlock(source))
				} else {
					result.Content = append(result.Content, content.VideoBlock(source))
				}
			}
		}
	}
	if response.Status != "completed" {
		return result, p.failure(
			media.ErrorProtocol,
			"Interactions response status %q",
			response.Status,
		)
	}
	if err := result.Validate(); err != nil {
		return result, p.failure(media.ErrorProtocol, "%w", err)
	}
	return result, nil
}

func (p *InteractionsMediaClient) inputPart(b content.Block) (any, error) {
	switch b.Kind {
	case content.KindText:
		if len(b.Text.Citations) > 0 {
			return nil, p.failure(
				media.ErrorUnsupported,
				"Interactions prompt citations",
			)
		}
		return map[string]any{"type": "text", "text": b.Text.Text}, nil
	case content.KindImage:
		source := b.Image.Source.WithDetectedMIMEType("")
		if b.Image.Detail != "" || source.Data == nil || !strings.HasPrefix(
			source.MIMEType,
			"image/",
		) {
			return nil, p.failure(
				media.ErrorUnsupported,
				"Interactions requires inline image bytes without detail",
			)
		}
		return map[string]any{
			"type":      "image",
			"mime_type": source.MIMEType,
			"data":      base64.StdEncoding.EncodeToString(source.Data),
		}, nil
	default:
		return nil, p.failure(
			media.ErrorUnsupported,
			"Interactions prompt block %q",
			b.Kind,
		)
	}
}
